export { app };

export default {
	// `PORT` lets several worktrees run side by side: `scripts/dev.ts` picks a
	// free port and hands it over, along with the matching `API_PROXY_TARGET`
	// for the web dev server.
	port: Number(process.env.PORT) || 3000,
	fetch: app.fetch,
};
